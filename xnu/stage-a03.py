#!/usr/bin/env python3
"""Stage the local A03 patch series into a darwin-xnu-build checkout.

This script does NOT vendor any third-party patches. It copies only
xnu/patches-a03/*.patch (generated by tools/gen_a03_patches.py) into
<builder>/patches/26.0, adds plain arm64 to the toolchain architectures, and
makes a rejected A03 patch a hard error instead of a warning.

An external donor series (Bergamota) is still required for a non-Apple SoC;
pass --donor PATH if you already have a local checkout. Those files are copied
but never stored in this repository.

Usage:
    python3 xnu/stage-a03.py --builder /path/to/darwin-xnu-build \
        [--donor /path/to/Bergamota]
"""

import argparse
from hashlib import sha256
from pathlib import Path

HERE = Path(__file__).resolve().parent
PATCH_VERSION = "26.0"
PREFIX = "9000-a03-"
FIREHOSE = 'ARCHS="x86_64 arm64e" VALID_ARCHS="x86_64 arm64e"'
REJECTED = '                warning "Skipping patch ${PATCH}'


def stage(builder: Path, donor: Path | None):
    patches = builder / "patches" / PATCH_VERSION
    if not patches.is_dir():
        raise SystemExit(f"missing {patches}: use the pinned darwin-xnu-build revision")

    build_sh = builder / "build.sh"
    source = build_sh.read_text(encoding="utf-8")
    if source.count(FIREHOSE) != 1 or source.count(REJECTED) != 1:
        raise SystemExit("unexpected darwin-xnu-build layout, use revision "
                         "663906528d1cd5ea8fde7de6f16de73db9511549")
    guard = (
        '                case "${PATCH##*/}" in\n'
        '                    *a03-*.patch) printf "Required A03 patch rejected: %s\\n%s\\n" '
        '"$PATCH" "$APPLY_CHECK" >&2; exit 1 ;;\n'
        '                esac\n'
    )
    build_sh.write_text(
        source.replace(FIREHOSE, FIREHOSE.replace("arm64e", "arm64e arm64"))
              .replace(REJECTED, guard + REJECTED),
        encoding="utf-8", newline="\n")

    staged = []
    if donor is not None:
        donor_series = donor / "xnu" / "patches-12377"
        if not donor_series.is_dir():
            raise SystemExit(f"missing {donor_series}")
        for patch in sorted(donor_series.glob("*.patch")):
            dest = patches / patch.name
            if dest.exists():
                raise SystemExit(f"duplicate patch: {dest.name}")
            dest.write_bytes(patch.read_bytes().replace(b"\r\n", b"\n"))
            staged.append(dest)

    for patch in sorted((HERE / "patches-a03").glob("*.patch")):
        dest = patches / (PREFIX + patch.name)
        if dest.exists():
            raise SystemExit(f"duplicate patch: {dest.name}")
        dest.write_bytes(patch.read_bytes().replace(b"\r\n", b"\n"))
        staged.append(dest)

    sums = builder / "series-SHA256SUMS"
    sums.write_text(
        "".join(f"{sha256(p.read_bytes()).hexdigest()}  {p.name}\n"
                for p in sorted(staged, key=lambda x: x.name)),
        encoding="utf-8", newline="\n")
    print(f"Staged {len(staged)} patch(es) in {patches}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--builder", type=Path, required=True)
    parser.add_argument("--donor", type=Path, help="local Bergamota checkout (not vendored)")
    args = parser.parse_args()
    stage(args.builder, args.donor)
